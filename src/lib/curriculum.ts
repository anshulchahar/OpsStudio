function mission(
  chapter: number,
  id: string,
  title: string,
  subtitle: string,
  action: ActionId,
  cta: string,
  brief: string,
  concept: string,
  hints: string[],
  question: string,
  options: [string, string, string],
  correct: number,
  explanation: string,
  reference: [string, string],
  lab?: Mission["lab"],
): Mission {
  return {
    id,
    title,
    subtitle,
    chapter,
    duration: chapter < 2 ? 8 : 12,
    action,
    cta,
    brief,
    concept,
    hints,
    decision: { question, options, correct, explanation },
    reference: { title: reference[0], url: reference[1] },
    lab,
  };
}

